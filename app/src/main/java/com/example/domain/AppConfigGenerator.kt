package com.example.domain

import android.util.Base64
import com.example.data.local.BuildItemEntity
import org.json.JSONObject

object AppConfigGenerator {

    /**
     * Generates clean Kotlin source code for AppConfig.kt
     */
    fun generateAppConfigKotlin(
        webUrl: String,
        appName: String,
        showTopBar: Boolean = false,
        showUrlBar: Boolean = false,
        pullToRefresh: Boolean = true,
        allowExternalIntents: Boolean = true,
        desktopMode: Boolean = false,
        offlinePwa: Boolean = false,
        clearCacheOnStart: Boolean = false,
        webShare: Boolean = true
    ): String {
        val sanitizedTitle = appName.replace("\"", "\\\"")
        val sanitizedUrl = webUrl.trim()

        return """
            package com.example

            /**
             * GENERATED BY FAIZ FAHMI ID — WEB TO APK BUILDER
             * Automated configuration for Android WebView Master Template
             */
            object AppConfig {
                const val WEB_URL = "$sanitizedUrl"
                const val APP_TITLE = "$sanitizedTitle"
                const val SHOW_TOP_BAR = $showTopBar
                const val SHOW_URL_BAR = $showUrlBar
                const val ENABLE_PULL_TO_REFRESH = $pullToRefresh
                const val ALLOW_EXTERNAL_INTENTS = $allowExternalIntents
                const val DESKTOP_MODE = $desktopMode
                const val ENABLE_OFFLINE_PWA_MODE = $offlinePwa
                const val CLEAR_CACHE_ON_START = $clearCacheOnStart
                const val ENABLE_WEB_SHARE = $webShare
            }
        """.trimIndent()
    }

    /**
     * Encodes file content to Base64 for GitHub Git API
     */
    fun encodeBase64(content: String): String {
        return Base64.encodeToString(content.toByteArray(Charsets.UTF_8), Base64.NO_WRAP)
    }

    /**
     * Converts build configuration to the contract JSON schema specified in prompt
     */
    fun buildContractJson(build: BuildItemEntity): String {
        val json = JSONObject().apply {
            put("buildId", build.id)
            put("webUrl", build.webUrl)
            put("appName", build.appName)
            put("packageName", build.packageName)
            put("iconUrl", build.iconUrl)
            put("orientation", build.orientation)
            put("buildType", build.buildType)
            put("fullscreen", build.fullscreen)
            put("showUrlBar", build.showUrlBar)
            put("javascript", build.javascript)
            put("pullToRefresh", build.pullToRefresh)
            put("externalIntents", build.externalIntents)
            put("offlinePwa", build.offlinePwa)
            put("desktopMode", build.desktopMode)
            put("nativeShare", build.nativeShare)
            put("fileUpload", build.fileUpload)
            put("downloads", build.downloads)
            put("splash", build.splash)
            put("splashDurationMs", build.splashDurationMs)
            put("splashBgColor", build.splashBgColor)
            put("createdAt", build.createdAt)
        }
        return json.toString(2)
    }
}
